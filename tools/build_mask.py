"""Build the Teldrassil pilot mask from Leeroy's Kalimdor coverage tiles."""

import argparse
from pathlib import Path

CELLS_PER_TILE = 128
# Bounds in the original 256 px minimap tiles, relative to tile (12, 29).
# Keep Dolanaar's paving and the Shadowglen approach within the pilot.
LEFT, TOP, RIGHT, BOTTOM = 272, 80, 510, 438
# Low coverage includes the textured road edges between full coverage cells.
THRESHOLD = 32


def generate(tiles: Path) -> str:
    origin_row = 12 * CELLS_PER_TILE + TOP // 2
    origin_column = 29 * CELLS_PER_TILE + LEFT // 2
    rows = (BOTTOM - TOP) // 2
    columns = (RIGHT - LEFT) // 2
    tiles_by_position = {}
    covered_cells = set()
    for row in range(origin_row, origin_row + rows):
        for column in range(origin_column, origin_column + columns):
            tile_row, local_row = divmod(row, CELLS_PER_TILE)
            tile_column, local_column = divmod(column, CELLS_PER_TILE)
            key = tile_row, tile_column
            if key not in tiles_by_position:
                data = (tiles / f"{tile_row}_{tile_column}.bin").read_bytes()
                if len(data) != CELLS_PER_TILE ** 2:
                    raise ValueError(f"Unexpected raster size in tile {key}")
                tiles_by_position[key] = data
            data = tiles_by_position[key]
            coverage_value = data[local_row * CELLS_PER_TILE + local_column]
            if coverage_value >= THRESHOLD:
                covered_cells.add((row, column))

    # Store consecutive active cells as inclusive ranges for a small build input.
    spans = []
    for row in range(origin_row, origin_row + rows):
        start = None
        for column in range(origin_column, origin_column + columns + 1):
            if (row, column) in covered_cells:
                if start is None:
                    start = column
            elif start is not None:
                first = (row - origin_row) * columns + start - origin_column
                spans.append(f"    {{{first}, {first + column - start - 1}}},")
                start = None

    if not spans:
        raise ValueError("The pilot raster contains no covered surfaces")
    return "\n".join([
        "// Generated by tools/build_mask.py from Leeroy's client-data output.",
        "#pragma once",
        "",
        "namespace RoadMask",
        "{",
        f"constexpr int OriginRow = {origin_row};",
        f"constexpr int OriginColumn = {origin_column};",
        f"constexpr int Rows = {rows};",
        f"constexpr int Columns = {columns};",
        "struct Span { int First; int Last; };",
        "constexpr Span Coverage[] =",
        "{",
        *spans,
        "};",
        "}",
        "",
    ])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tiles", type=Path, help="Leeroy's roads/1 directory")
    parser.add_argument("output", type=Path, help="Path to RoadMask.generated.h")
    args = parser.parse_args()
    args.output.write_text(generate(args.tiles), encoding="utf-8")
