"""Build a C++ road mask from Leeroy's 3.3.5a coverage tiles."""

import argparse
from pathlib import Path

MAP_IDS = (0, 1, 530, 571)
TILES_PER_SIDE = 64
CELLS_PER_TILE = 128
# Low coverage includes painted road edges between full coverage cells.
THRESHOLD = 32


def generate(tiles: Path) -> str:
    spans = []
    tile_entries = []

    for map_id in MAP_IDS:
        files = {}
        for path in (tiles / str(map_id)).glob("*.bin"):
            row, column = map(int, path.stem.split("_"))
            if not (0 <= row < TILES_PER_SIDE and 0 <= column < TILES_PER_SIDE):
                raise ValueError(f"Invalid tile coordinates in {path}")
            key = (map_id * TILES_PER_SIDE + row) * TILES_PER_SIDE + column
            if key in files:
                raise ValueError(f"Duplicate tile coordinates in {path}")
            files[key] = path
        if not files:
            raise ValueError(f"No coverage tiles found for map {map_id}")

        for key, path in sorted(files.items()):
            data = path.read_bytes()
            if len(data) != CELLS_PER_TILE ** 2:
                raise ValueError(f"Unexpected raster size in {path}")
            begin = len(spans)
            start = None
            for cell, value in enumerate(data + b"\0"):
                if value >= THRESHOLD:
                    if start is None:
                        start = cell
                elif start is not None:
                    spans.append(f"    {{{start}, {cell - 1}}},")
                    start = None
            if begin != len(spans):
                tile_entries.append(f"    {{{key}, {begin}, {len(spans)}}},")

    if not spans:
        raise ValueError("The rasters contain no covered surfaces")
    return "\n".join([
        "// Generated by tools/build_mask.py from Leeroy's client-data output.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace RoadMask",
        "{",
        f"constexpr int TilesPerSide = {TILES_PER_SIDE};",
        f"constexpr int CellsPerTile = {CELLS_PER_TILE};",
        "struct Span { std::uint16_t First; std::uint16_t Last; };",
        "struct Tile { std::uint32_t Key; std::uint32_t Begin; std::uint32_t End; };",
        "constexpr Span Coverage[] =",
        "{",
        *spans,
        "};",
        "constexpr Tile Tiles[] =",
        "{",
        *tile_entries,
        "};",
        "}",
        "",
    ])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("tiles", type=Path, help="Leeroy's roads directory with map subdirectories")
    parser.add_argument("output", type=Path, help="Path to RoadMask.generated.h")
    args = parser.parse_args()
    args.output.write_text(generate(args.tiles), encoding="utf-8")
